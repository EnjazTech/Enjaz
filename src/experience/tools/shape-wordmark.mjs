/**
 * Shapes إنجاز with HarfBuzz at build time and writes its outlines to
 * generated/wordmark.js, so the real Kufi letterforms can be extruded at runtime
 * with no font, no shaper and no WASM in the browser (the CSP forbids WASM).
 *
 *   node tools/shape-wordmark.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as hb from "harfbuzzjs";
import wawoff2 from "wawoff2";

const HERE = new URL(".", import.meta.url);
const WOFF2 = fileURLToPath(new URL("../../../assets/fonts/noto-kufi-arabic-400-700-arabic.woff2", HERE));
const OUT = fileURLToPath(new URL("../generated/wordmark.js", HERE));

const ttf = await wawoff2.decompress(readFileSync(WOFF2));
const face = new hb.Face(new hb.Blob(ttf.buffer.slice(ttf.byteOffset, ttf.byteOffset + ttf.byteLength)));
const font = new hb.Font(face);
font.setVariations([new hb.Variation("wght", 700)]);

const buffer = new hb.Buffer();
buffer.addText("إنجاز");
buffer.guessSegmentProperties();
hb.shape(font, buffer);
const infos = buffer.getGlyphInfos();
const positions = buffer.getGlyphPositions();

/* Glyphs come back in visual order, left to right. */
let penX = 0;
const shapes = [];
infos.forEach((info, index) => {
  const place = positions[index];
  const path = font.glyphToPath(info.codepoint);
  if (path) {
    const flat = [];
    for (const [, type, numbers] of path.matchAll(/([MLQCZ])([^MLQCZ]*)/g)) {
      const values = numbers.trim().split(/[\s,]+/).filter(Boolean).map(Number);
      flat.push(type, ...values.map((value, at) => Math.round(at % 2 === 0 ? value + penX + place.xOffset : value + place.yOffset)));
    }
    shapes.push(flat);
  }
  penX += place.xAdvance;
});

let minX = Infinity;
let maxX = -Infinity;
let minY = Infinity;
let maxY = -Infinity;
const extents = shapes.map((flat) => {
  let lo = Infinity;
  let hi = -Infinity;
  for (let i = 0; i < flat.length; ) {
    const count = { M: 2, L: 2, Q: 4, C: 6, Z: 0 }[flat[i]];
    for (let k = 0; k < count; k += 2) {
      const x = flat[i + 1 + k];
      const y = flat[i + 2 + k];
      lo = Math.min(lo, x);
      hi = Math.max(hi, x);
      minX = Math.min(minX, x);
      maxX = Math.max(maxX, x);
      minY = Math.min(minY, y);
      maxY = Math.max(maxY, y);
    }
    i += 1 + count;
  }
  return [lo, hi];
});

/* The widest clean gap between letters: the camera threads it, and no join is cut. */
const sorted = [...extents].sort((a, b) => a[0] - b[0]);
let gap = [0, 0];
for (let i = 0; i < sorted.length - 1; i += 1) {
  const lo = sorted[i][1];
  const hi = sorted[i + 1][0];
  if (hi - lo > gap[1] - gap[0]) {
    gap = [lo, hi];
  }
}

const body = `/* Generated by tools/shape-wordmark.mjs. Do not edit. Noto Kufi Arabic, wght 700, shaped with HarfBuzz. */
export const WORDMARK = ${JSON.stringify({ shapes, bounds: [minX, minY, maxX, maxY], gap })};
`;
writeFileSync(OUT, body);
console.log(`shapes=${shapes.length} bounds=${[minX, minY, maxX, maxY]} gap=${gap} bytes=${body.length}`);
